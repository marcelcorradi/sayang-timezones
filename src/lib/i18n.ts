export function translate(lang: Lang, key: TranslationKey, vars: Record<string, string | number> = {}) {
  return DICTIONARIES[lang][key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`))
}

export function formatDuration(ms: number, lang: Lang) {
  const total = Math.max(1, Math.round(ms / 60_000))
  const h = Math.floor(total / 60)
  const m = total % 60
  const parts: string[] = []
  if (h) parts.push(translate(lang, "hoursShort", { h }))
  if (m || !h) parts.push(translate(lang, "minutesShort", { m }))
  return parts.join(" ")
}

export function detectLang(): Lang {
  const nav = typeof navigator !== "undefined" ? navigator.language.toLowerCase() : "en"
  if (nav.startsWith("pt")) return "pt"
  if (nav.startsWith("id") || nav.startsWith("in")) return "id"
  return "en"
}
